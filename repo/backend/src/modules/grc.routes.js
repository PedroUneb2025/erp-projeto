const express = require('express');
const pool = require('../db/pool');
const { makeCrud, routerDe } = require('./crud');
const { exigir } = require('../middleware/auth');
const r = express.Router();
r.use(exigir('DIRETOR'));
r.use('/risco', routerDe(makeCrud(pool, 'grc.risco', ['id','descricao','probabilidade','impacto','mitigacao'], 'id'), { criar: true, atualizar: true }));
r.use('/consentimento-lgpd', routerDe(makeCrud(pool, 'grc.consentimento_lgpd', ['id','titular_tipo','titular_id','finalidade','consentido'], 'id'), { criar: true, atualizar: true }));
r.use('/sod-regra', routerDe(makeCrud(pool, 'grc.sod_regra', ['id','perfil_a','perfil_b','descricao'], 'id')));
r.use('/auditoria-interna', routerDe(makeCrud(pool, 'grc.auditoria_interna', ['id','escopo','inicio','fim','parecer','conformidade'], 'id')));
module.exports = r;
